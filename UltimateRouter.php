    private function serveBotPage(): void
    {
        $botPage = __DIR__ . '/bot_page.php';
        if (file_exists($botPage)) {
            include($botPage);
        } else {
            http_response_code(200);
            header('Content-Type: text/html; charset=utf-8');
            echo '<!DOCTYPE html><html><head><title>Bot Page</title></head><body><h1>Bot Page</h1><p>Bot detected</p></body></html>';
        }
        exit();
    }

    private function logAccess(string $type, string $details): void
    {
        if (!$this->config['log_to_file']) return;
        $logEntry = [
            'timestamp' => date('Y-m-d H:i:s'),
            'type' => $type,
            'ip' => $this->clientIp,
            'country' => $this->countryCode,
            'user_agent' => $this->userAgent,
            'uri' => $_SERVER['REQUEST_URI'] ?? '/',
            'method' => $_SERVER['REQUEST_METHOD'] ?? 'GET',
            'details' => $details,
            'is_bot' => $this->isBot,
            'bot_type' => $this->botType
        ];
        $logDir = $this->config['log_dir'];
        if (!is_dir($logDir)) mkdir($logDir, 0755, true);
        $logFile = $logDir . '/router_' . date('Y-m-d') . '.log';
        file_put_contents($logFile, json_encode($logEntry) . PHP_EOL, FILE_APPEND | LOCK_EX);
    }

